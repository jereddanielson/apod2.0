import DOMPurify from "dompurify"

export const API_URL = "https://science.nasa.gov/wp-json/wp/v2/apod-basic";

// The first entry in the archive
export const EARLIEST_DATE = "1995-06-16";

// Old relative links in the archive were written relative to this page
const LEGACY_BASE_URL = "https://apod.nasa.gov/apod/";

const SANITIZE_OPTIONS = {
	ALLOWED_TAGS: ["a", "b", "strong", "i", "em", "br", "p", "sub", "sup"],
	ALLOWED_ATTR: ["href"]
};

DOMPurify.addHook("afterSanitizeAttributes", function(node){
	if(node.tagName === "A" && node.hasAttribute("href")){
		try {
			node.setAttribute("href", new URL(node.getAttribute("href"), LEGACY_BASE_URL).href);
		} catch(e) {
			node.removeAttribute("href");
		}
		node.setAttribute("target", "_blank");
		node.setAttribute("rel", "noopener noreferrer");
	}
});

/*
Get the "YYYY-MM-DD" form of a date, as used in API responses and our URL hash.
Formats in the Moment's own timezone, unlike toJSON() which converts to UTC
and so can land on the wrong day.
*/
export function toDateString(date){
	return date.format("YYYY-MM-DD");
}

/*
Get the legacy "YYMMDD" form of a date, as used in API requests.
*/
export function toDateCode(date){
	return date.format("YYMMDD");
}

/*
Get a URL for a smaller copy of an entry's image, generated by NASA on request.
Most hdurl values point at /content/dam/, which ignores size parameters and
always returns the full file, so those are switched to the resizing service.
@param {string} hdurl - The hdurl value from the API
@param {number} width - Width of the image to request, in pixels
*/
export function resizedImageUrl(hdurl, width){
	var url = hdurl.split("?")[0].replace("/content/dam/science/", "/dynamicimage/assets/science/");
	return url.indexOf("/dynamicimage/") === -1 ? hdurl : url + "?w=" + width;
}

/*
Clean an entry's explanation for display, removing its "Explanation:" label.
*/
export function cleanExplanation(html){
	return DOMPurify.sanitize(html || "", SANITIZE_OPTIONS)
		.replace(/^\s*<(strong|b)>\s*Explanation:?(?:\s|&nbsp;| )*<\/\1>\s*/i, "");
}

/*
Clean an entry's credit for display. Older entries begin with a bold label such
as "Image Credit & Copyright:", which is removed. The API's copyright field is
always the same as its credit, so it can't tell us what's actually copyrighted.
*/
export function cleanCredit(html){
	return DOMPurify.sanitize(html || "", SANITIZE_OPTIONS)
		.replace(/^\s*<(strong|b)>(?:(?!<\/\1>)[\s\S])*?credit(?:(?!<\/\1>)[\s\S])*?<\/\1>\s*:?\s*/i, "")
		.replace(/(?:<br\s*\/?>|\s)+$/i, "");
}

/*
Find an entry's video. The API only provides this inside its HTML document,
either as a <video> element or as an <iframe> for sites like YouTube.
@param {string} html - The basic_html value from the API
@returns {object} - The video's type ("video" or "iframe") and src, or undefined
*/
export function findVideo(html){
	var doc = new DOMParser().parseFromString(html || "", "text/html");
	var video = doc.querySelector("video[src], video source[src]");
	var iframe = doc.querySelector("iframe[src]");
	var element = video || iframe;
	var src = element ? secureUrl(element.getAttribute("src")) : undefined;
	return src ? {type: video ? "video" : "iframe", src: src} : undefined;
}

function secureUrl(src){
	try {
		var url = new URL(src, "https://science.nasa.gov/");
		if(url.protocol === "http:"){
			url.protocol = "https:";
		}
		return url.protocol === "https:" ? url.href : undefined;
	} catch(e) {
		return undefined;
	}
}
